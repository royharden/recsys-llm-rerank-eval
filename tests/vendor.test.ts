import { describe,expect,it } from 'vitest';
import { readFile,readdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const vendor = path.join(root,'supabase/functions/rerank/_vendor');
const header = '// GENERATED by scripts/sync-function-vendor.ts; edit the repository source, then sync.\n';
async function files(dir: string): Promise<string[]> {
  const out:string[] = [];
  for (const e of await readdir(path.join(root,dir),{withFileTypes:true})) {
    const rel = path.posix.join(dir,e.name);
    if (e.isDirectory()) out.push(...await files(rel)); else if (/\.(ts|json)$/.test(e.name)) out.push(rel);
  }
  return out;
}
describe('edge vendor closure (source contract, not a Deno deployment test)',() => {
  it('copies every allowed source exactly except header and the one zod specifier rewrite',async () => {
    const sources = ['config/prices.json'];
    for (const dir of ['src/core/util','src/core/prompts','src/core/rerankguard','src/core/contracts','config/prompts']) sources.push(...await files(dir));
    for (const rel of sources) {
      const source = await readFile(path.join(root,rel),'utf8');
      const copied = await readFile(path.join(vendor,rel),'utf8');
      expect(copied,rel).toBe(rel.endsWith('.ts') ? header+source.replace(/from (['"])zod\1/g,"from 'npm:zod@3.23.8'") : source);
      if (!rel.endsWith('.ts')) continue;
      for (const match of copied.matchAll(/^\s*(?:import|export)\b[^;]*?\bfrom\s+['"]([^'"]+)['"]/gm)) {
        const spec = match[1];
        if (spec === 'npm:zod@3.23.8') continue;
        expect(spec,`${rel}: unexpected external import`).toMatch(/^\./);
        const resolved = path.resolve(vendor,path.dirname(rel),spec);
        expect(resolved.startsWith(vendor+path.sep),`${rel}: escaped closure`).toBe(true);
        expect(await readFile(resolved,'utf8')).toBeTruthy();
      }
    }
  });
});
