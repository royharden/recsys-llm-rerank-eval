// Source-generation only. Generated layout mirrors repo paths so every relative import keeps its original meaning.
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const vendor = path.join(root,'supabase/functions/rerank/_vendor');
export const VENDOR_HEADER = '// GENERATED by scripts/sync-function-vendor.ts; edit the repository source, then sync.\n';
export function transformVendor(source: string): string {
  return VENDOR_HEADER + source.replace(/from (['"])zod\1/g,"from 'npm:zod@3.23.8'");
}
async function copyTree(relative: string): Promise<void> {
  const from = path.join(root,relative);
  for (const entry of await readdir(from,{withFileTypes:true})) {
    const child = path.join(relative,entry.name);
    if (entry.isDirectory()) await copyTree(child);
    else if (entry.isFile() && /\.(ts|json)$/.test(entry.name)) {
      const source = await readFile(path.join(root,child),'utf8');
      const target = path.join(vendor,child); await mkdir(path.dirname(target),{recursive:true});
      // JSON cannot carry a comment header; provenance is in _vendor/PROVENANCE.md and exact-copy tests.
      await writeFile(target,entry.name.endsWith('.ts') ? transformVendor(source) : source,'utf8');
    }
  }
}
// Invoking sync writes source assets only; it never installs, executes the application, or fetches upstream code.
for (const dir of ['src/core/util','src/core/prompts','src/core/rerankguard','src/core/contracts','config/prompts']) await copyTree(dir);
await mkdir(path.join(vendor,'config'),{recursive:true});
await writeFile(path.join(vendor,'config/prices.json'),await readFile(path.join(root,'config/prices.json'),'utf8'),'utf8');
await writeFile(path.join(vendor,'PROVENANCE.md'),'# Generated vendor closure\n\nSources: src/core/{util,prompts,rerankguard,contracts}, config/prices.json, config/prompts/*.json.\nTypeScript copies add the generated header and rewrite only the zod specifier to npm:zod@3.23.8. JSON copies are byte-identical.\nNo third-party source is vendored. Run npm run sync:vendor after editing any source in this closure; test with npm test -- tests/vendor.test.ts.\n','utf8');
