// Frozen split manifest (PLAN §3). The salt is an INPUT: freezeManifest receives fresh random hex from the caller
// (node:crypto / Web Crypto); loadManifest reuses a stored salt. The pure core never generates randomness.
import { z } from 'zod';
import type { Dataset, Interaction, ValidationReport } from '../data/types.ts';
import { HEX64, hashCanonical, shortKey } from '../util/hash.ts';
import { splitAt, type QDecision, type SplitResult } from './temporal.ts';

export const CORE_VERSION = '0.1.0';
export const SALT_HEX = /^[0-9a-f]{32}$/; // 16 random bytes

const hex64 = z.string().regex(HEX64, 'must be 64 lowercase hex characters');
const count = z.number().int().nonnegative();

export const ManifestSchema = z
  .object({
    schemaVersion: z.literal(1),
    coreVersion: z.string().min(1),
    seed: z.number().int(),
    q: z.number().gt(0).lte(1),
    T: z.number().int().nonnegative(),
    minHistory: z.number().int().positive(),
    minHeldout: count,
    insufficientPrecision: z.boolean(),
    qTrials: z.array(z.object({ q: z.number(), T: z.number().int(), eligible: count, dev: count, heldout: count }).strict()),
    files: z.object({ uData: hex64, uItem: hex64 }).strict(),
    datasetHash: hex64,
    counts: z
      .object({
        interactions: count,
        users: count,
        items: count,
        catalogue: count,
        eligible: count,
        dev: count,
        heldout: count,
        coldTargets: count,
        exclusions: z.object({ insufficient_history: count, no_target: count }).strict(),
        rejectedLines: count,
      })
      .strict(),
    salt: z.string().regex(SALT_HEX, 'salt must be 32 lowercase hex characters'),
    frozenAt: z.string().datetime(),
    manifestHash: hex64,
  })
  .strict();

export type Manifest = z.infer<typeof ManifestSchema>;
export type ManifestBody = Omit<Manifest, 'frozenAt' | 'manifestHash'>;

/** manifestHash = sha256(canonical JSON of the manifest without frozenAt and without manifestHash itself). */
export function computeManifestHash(m: ManifestBody | Manifest): string {
  const body: Record<string, unknown> = { ...m };
  delete body.frozenAt;
  delete body.manifestHash;
  return hashCanonical(body);
}

/** Pseudonymous user key: first 16 hex of sha256(salt|userId). Not anonymous: anyone with the salt can map it back. */
export function userKeyOf(salt: string, userId: number): string {
  return shortKey([salt, userId], 16);
}

export interface FreezeInput {
  dataset: Dataset;
  report: ValidationReport;
  decision: QDecision;
  split: SplitResult;
}

export interface FreezeOptions {
  /** 32 hex chars from a cryptographic RNG, generated by the caller exactly once per dataset. */
  randomSaltHex: string;
  /** ISO-8601 UTC timestamp (`new Date().toISOString()`), supplied by the caller; excluded from manifestHash. */
  frozenAt: string;
}

/** First-freeze path: builds a new manifest around a caller-supplied salt. Never call it when a lock/run already exists. */
export function freezeManifest(input: FreezeInput, opts: FreezeOptions): Manifest {
  const { dataset, report, decision, split } = input;
  if (!SALT_HEX.test(opts.randomSaltHex)) throw new Error('freezeManifest: randomSaltHex must be 32 lowercase hex characters');
  if (split.T !== decision.T) throw new Error('freezeManifest: split T does not match the q decision');
  const body: ManifestBody = {
    schemaVersion: 1,
    coreVersion: CORE_VERSION,
    seed: split.seed,
    q: decision.q,
    T: decision.T,
    minHistory: split.minHistory,
    minHeldout: decision.minHeldout,
    insufficientPrecision: decision.insufficientPrecision,
    qTrials: decision.trials.map((t) => ({ ...t })),
    files: { uData: dataset.hashes.uData, uItem: dataset.hashes.uItem },
    datasetHash: dataset.hashes.datasetHash,
    counts: {
      interactions: dataset.interactions.length,
      users: report.users,
      items: dataset.items.length,
      catalogue: split.catalogue.length,
      eligible: split.eligibleUserIds.length,
      dev: split.devUserIds.length,
      heldout: split.heldoutUserIds.length,
      coldTargets: split.coldTargetUserIds.length,
      exclusions: { ...split.exclusions },
      rejectedLines: report.rejectCount,
    },
    salt: opts.randomSaltHex,
  };
  const manifest: Manifest = { ...body, frozenAt: opts.frozenAt, manifestHash: computeManifestHash(body) };
  const checked = ManifestSchema.safeParse(manifest);
  if (!checked.success) throw new Error(`freezeManifest: invalid manifest: ${checked.error.issues[0].message}`);
  return manifest;
}

export type ManifestLoad = { ok: true; manifest: Manifest } | { ok: false; error: string };

/** Load path: validate a stored manifest (lock file or eval_runs.config.manifest) and reuse its salt unchanged. */
export function loadManifest(stored: unknown, expect?: { datasetHash?: string }): ManifestLoad {
  const parsed = ManifestSchema.safeParse(stored);
  if (!parsed.success) {
    const i = parsed.error.issues[0];
    return { ok: false, error: `invalid manifest at ${i.path.join('.') || '$'}: ${i.message}` };
  }
  const manifest = parsed.data;
  if (computeManifestHash(manifest) !== manifest.manifestHash) return { ok: false, error: 'manifestHash does not match manifest contents' };
  if (expect?.datasetHash !== undefined && expect.datasetHash !== manifest.datasetHash) {
    return { ok: false, error: 'dataset does not match the stored manifest (datasetHash differs)' };
  }
  return { ok: true, manifest };
}

/** Re-derive the split from a stored manifest's T and seed (never re-choosing q), and check it reproduces the frozen counts. */
export function splitFromManifest(
  dataset: { interactions: readonly Interaction[]; hashes: { datasetHash: string } },
  manifest: Manifest,
): { ok: true; split: SplitResult } | { ok: false; error: string } {
  if (dataset.hashes.datasetHash !== manifest.datasetHash) return { ok: false, error: 'datasetHash differs from manifest' };
  const split = splitAt(dataset.interactions, manifest.T, { seed: manifest.seed, minHistory: manifest.minHistory });
  const c = manifest.counts;
  const same =
    split.catalogue.length === c.catalogue &&
    split.eligibleUserIds.length === c.eligible &&
    split.devUserIds.length === c.dev &&
    split.heldoutUserIds.length === c.heldout &&
    split.coldTargetUserIds.length === c.coldTargets;
  return same ? { ok: true, split } : { ok: false, error: 'split re-derived from manifest does not reproduce its counts' };
}
